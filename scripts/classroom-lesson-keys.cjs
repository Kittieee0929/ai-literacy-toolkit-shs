const path = require('node:path');

global.window = {};
for (const file of ['lesson-data', 'more-lesson-data', 'practice-lesson-data']) {
  require(path.resolve(__dirname, '..', 'js', file + '.js'));
}
const lessons = Object.values({...window.AILiteracyLessons, ...window.AILiteracyMoreLessons});

function answerKey(question) {
  return {
    kind: question.type || 'single',
    choices: (question.items || question.options).length,
    correct: question.correct
  };
}

const rows = lessons.map(lesson => {
  const quiz = JSON.stringify(lesson.quiz.map(answerKey));
  const assessment = JSON.stringify(lesson.assessment.map(answerKey));
  return `  (${lesson.id}, '${quiz}'::jsonb, '${assessment}'::jsonb)`;
});
process.stdout.write(`-- Generated by scripts/classroom-lesson-keys.cjs.\ninsert into classroom_private.lesson_keys(lesson_id,quiz,assessment) values\n${rows.join(',\n')}\non conflict (lesson_id) do update set quiz=excluded.quiz, assessment=excluded.assessment;\n`);
